/**
 * 模拟 / 真实接口加载器：支持从后端 API 动态拉取国家列表或回退至内置全量字典
 * @param apiEndpoint 可选的后端接口地址，如 '/index/getcountry'
 */
export async function fetchCountryPhoneList(apiEndpoint?: string): Promise<CountryPhoneRule[]> {
  if (apiEndpoint && typeof window !== 'undefined' && typeof window.fetch === 'function') {
    try {
      const resp = await fetch(apiEndpoint, { method: 'POST' });
      const json = await resp.json();
      if (json && json.code === 0 && Array.isArray(json.data?.list)) {
        return json.data.list.map((item: any) => ({
          iso2: (item.code || '').toLowerCase(),
          dialCode: (item.mobile_code || item.dialCode || '').replace('+', ''),
          code: item.code ? '+' + (item.mobile_code || item.dialCode) : '+65',
          name: item.name_en || item.name || '',
          zh: item.name || item.name_en || '',
          flag: item.flag || '',
          placeholder: '8123 4567',
          minLength: 6,
          maxLength: 15
        }));
      }
    } catch {
      // 接口失败时静默回退全量内置字典
    }
  }
  return allCountryPhoneRules;
}

/**
 * 快速匹配指定国家电话规则
 */
export function getCountryPhoneRule(codeOrDialOrIso?: string): CountryPhoneRule {
  if (!codeOrDialOrIso) return allCountryPhoneRules.find(c => c.iso2 === 'sg') || allCountryPhoneRules[0];
  const clean = codeOrDialOrIso.replace('+', '').toLowerCase();

  // 1. 优先匹配二字码 (如 'sg', 'cn')
  const byIso = allCountryPhoneRules.find(r => r.iso2 === clean);
  if (byIso) return byIso;

  // 2. 匹配完整代号 (如 '+65', '+86')
  const byCode = allCountryPhoneRules.find(r => r.code === codeOrDialOrIso);
  if (byCode) return byCode;

  // 3. 匹配纯数字区号 (如 '65', '86')
  const byDial = allCountryPhoneRules.find(r => r.dialCode === clean);
  if (byDial) return byDial;

  return allCountryPhoneRules.find(c => c.iso2 === 'sg') || allCountryPhoneRules[0];
}

/**
 * 校验手机号合法性 (严格国际规则 / 宽松规则)
 */
export function validatePhoneNumber(
  dialCode: string,
  rawNumber: string,
  strict: boolean = true
): { valid: boolean; message: string; message_en: string } {
  const digits = rawNumber.replace(/\D/g, '');
  if (!digits) {
    return { valid: false, message: '请输入手机号码', message_en: 'Please enter phone number' };
  }
  const rule = getCountryPhoneRule(dialCode);
  if (!strict) {
    if (digits.length < 6 || digits.length > 15) {
      return { valid: false, message: '请输入6-15位有效手机号码', message_en: 'Please enter 6-15 digit phone number' };
    }
    return { valid: true, message: '', message_en: '' };
  }

  // 严格规则校验
  if (digits.length < rule.minLength) {
    return {
      valid: false,
      message: `${rule.zh}手机号码至少需要 ${rule.minLength} 位数字`,
      message_en: `${rule.name} phone number requires at least ${rule.minLength} digits`
    };
  }
  if (digits.length > rule.maxLength) {
    return {
      valid: false,
      message: `${rule.zh}手机号码最多不能超过 ${rule.maxLength} 位数字`,
      message_en: `${rule.name} phone number cannot exceed ${rule.maxLength} digits`
    };
  }
  if (rule.pattern) {
    const reg = new RegExp(rule.pattern);
    if (!reg.test(digits)) {
      return {
        valid: false,
        message: `请输入有效的${rule.zh}手机号码（示例：${rule.placeholder}）`,
        message_en: `Please enter a valid ${rule.name} phone number (e.g. ${rule.placeholder})`
      };
    }
  }
  return { valid: true, message: '', message_en: '' };
}
